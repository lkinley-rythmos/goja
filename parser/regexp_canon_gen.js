// This script generates regexp_canon_tables.go: the classes of UTF-16 code
// units that ECMAScript's Canonicalize makes equivalent for a RegExp that
// ignores case without the u flag (ECMA-262 22.2.2.7.3): toUpperCase of the
// code unit, unless that is not one code unit, or maps a code unit from
// 128 up to one below 128. Node.js 18 (V8 10.2) is the reference, so the
// script must run under Node.js 18:
//
//	docker run --rm --network none -v "$PWD/parser:/out" \
//	  --entrypoint node <node 18 image> /out/regexp_canon_gen.js
//	gofmt -w parser/regexp_canon_tables.go

'use strict';

const fs = require('fs');

const OUT = '/out/regexp_canon_tables.go';

function canonicalize(u) {
    const s = String.fromCharCode(u).toUpperCase();
    if (s.length !== 1) {
        return u;
    }
    const cu = s.charCodeAt(0);
    if (u >= 128 && cu < 128) {
        return u;
    }
    return cu;
}

const classes = new Map();
for (let u = 0; u <= 0xffff; u++) {
    const c = canonicalize(u);
    if (!classes.has(c)) {
        classes.set(c, []);
    }
    classes.get(c).push(u);
}
const groups = [...classes.values()].filter((g) => g.length > 1).sort((a, b) => a[0] - b[0]);

let out = '// Code generated by regexp_canon_gen.js; DO NOT EDIT.\n\n';
out += `// Generated with Node.js ${process.version.slice(1)} (V8 ${process.versions.v8}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).\n\n`;
out += 'package parser\n\n';
out += '// regexpCanonClasses lists the classes of more than one code unit that\n';
out += '// Canonicalize makes equivalent without the u flag, each as its length and\n';
out += '// its code units, in order.\n';
out += 'var regexpCanonClasses = []uint16{\n';
for (const g of groups) {
    out += '\t' + g.length + ', ' + g.map((u) => '0x' + u.toString(16)).join(', ') + ',\n';
}
out += '}\n';
fs.writeFileSync(OUT, out);
console.log(groups.length + ' classes');
