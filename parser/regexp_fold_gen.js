// This script generates regexp_fold_tables.go: the classes of code points
// that a RegExp with the u and i flags matches as the same character (the
// case folding orbits). ECMA-262 relates two characters under the u flag if
// simple case folding maps them to the same one; V8 closes each character
// over ICU's case-insensitive closure, which also relates characters whose
// full case foldings are the same string (U+0390 and U+1FD3, U+FB05 and
// U+FB06). Node.js 18 (V8 10.2) is the reference, so the script must run
// under Node.js 18:
//
//	docker run --rm --network none -v "$PWD/parser:/out" \
//	  --entrypoint node <node 18 image> /out/regexp_fold_gen.js
//	gofmt -w parser/regexp_fold_tables.go
//
// It asks V8 itself which characters each character matches. Only
// characters with a case mapping, and the characters of their mappings, can
// match another; the script checks that no other character matches one of
// them, and that the relation is an equivalence.

'use strict';

const fs = require('fs');

const OUT = process.argv[2] || '/out/regexp_fold_tables.go';

const isSurrogate = (c) => c >= 0xd800 && c <= 0xdfff;
const cp = (c) => String.fromCodePoint(c);
const esc = (c) => '\\u{' + c.toString(16) + '}';

const candidates = new Set();
for (let c = 0; c <= 0x10ffff; c++) {
    if (isSurrogate(c)) continue;
    const s = cp(c);
    const lo = s.toLowerCase(), up = s.toUpperCase();
    if (lo !== s || up !== s) {
        candidates.add(c);
        for (const r of lo + up) {
            candidates.add(r.codePointAt(0));
        }
    }
}
const cands = [...candidates].sort((a, b) => a - b);
const candStr = cands.map(cp).join('');

// No character outside the candidates matches one of them.
let all = '';
for (let c = 0; c <= 0x10ffff; c++) {
    if (!isSurrogate(c)) all += cp(c);
}
const anyCand = new RegExp('[' + cands.map(esc).join('') + ']', 'giu');
const matched = all.match(anyCand).map((s) => s.codePointAt(0));
if (matched.length !== cands.length || matched.some((c, i) => c !== cands[i])) {
    throw new Error('a character outside the candidates matches one: ' +
        matched.filter((c) => !candidates.has(c)).map((c) => c.toString(16)).join(' '));
}

const orbitOf = new Map();
for (const c of cands) {
    const m = candStr.match(new RegExp(esc(c), 'giu')).map((s) => s.codePointAt(0));
    orbitOf.set(c, m);
}
// The relation is an equivalence: each character is in its orbit, and the
// characters of an orbit have the same one.
for (const [c, m] of orbitOf) {
    if (!m.includes(c)) throw new Error('not reflexive: ' + c.toString(16));
    for (const d of m) {
        const n = orbitOf.get(d);
        if (n.length !== m.length || n.some((x, i) => x !== m[i])) {
            throw new Error('not an equivalence: ' + c.toString(16) + ' ' + d.toString(16));
        }
    }
}
const orbits = [];
const seen = new Set();
for (const c of cands) {
    const m = orbitOf.get(c);
    if (m.length > 1 && !seen.has(m[0])) {
        seen.add(m[0]);
        orbits.push(m);
    }
}

let out = '// Code generated by regexp_fold_gen.js; DO NOT EDIT.\n\n';
out += `// Generated with Node.js ${process.version.slice(1)} (V8 ${process.versions.v8}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).\n\n`;
out += 'package parser\n\n';
out += '// regexpFoldOrbits lists the classes of more than one code point that a\n';
out += '// pattern with the u and i flags matches as the same character, each as\n';
out += '// its length and its code points, in order.\n';
out += 'var regexpFoldOrbits = []int32{\n';
for (const g of orbits) {
    out += '\t' + g.length + ', ' + g.map((u) => '0x' + u.toString(16)).join(', ') + ',\n';
}
out += '}\n';
fs.writeFileSync(OUT, out);
console.log(orbits.length + ' orbits, ' + orbits.reduce((n, g) => n + g.length, 0) + ' code points, ' + cands.length + ' candidates');
